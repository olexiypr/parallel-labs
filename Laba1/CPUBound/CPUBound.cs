public class CPUBound : BaseTest
{
    public void TestMonteKarlo()
    {
        var name = "MonteKarlo";
        var paramArr = new int [] {100000000, 1000000000};
        var threadsCounts = new int[] {1, 2, 5, 10, 20, 40};
        foreach (var param in paramArr)
        {
            LogBeginTest(name, param);
            foreach (var threadsCount in threadsCounts)
            {
                var monteKarlo = new MonteKarlo(threadsCount);
                TestAction(() => monteKarlo.CalculatePi(param), name, threadsCount);
            }
            
            LogCompletedTest(name);
        }
        
    }
    
    public void TestFactorization()
    {
        var name = "Factorization";
        var paramArr = new[] { BigInteger.Parse("100000000000000000000"), BigInteger.Parse("10000000000001107") };
        var threadsCounts = new int[] {2, 5, 10, 20, 40, 100};
        foreach (var input in paramArr)
        {
            LogBeginTest(name, input);
            var factorization = new Factorization(1);
            TestAction(() => factorization.CalculateSingleThread(input), name, 1);
            foreach (var threadsCount in threadsCounts)
            {
                factorization = new Factorization(threadsCount);
                TestAction(() => factorization.Calculate(input).GetAwaiter().GetResult(), name, threadsCount);
            }
            
            LogCompletedTest(name);
        }
    }

    public void TestSimpleNumbersCalculation()
    {
        var name = "SimpleNumbersCalculation";
        var paramArr = new int []{100000, 1000000, 2000000};
        var threadsCounts = new int[] {1, 2, 5, 10, 20, 40, 100};
        foreach (var inputParam in paramArr)
        {
            LogBeginTest(name, inputParam);
            foreach (var threadsCount in threadsCounts)
            {
                var simpleNumbersCalculation = new SimpleNumbersCalculation(threadsCount);
                var param = inputParam;
                TestAction(() => simpleNumbersCalculation.Calculate(param), name, threadsCount);
            }
            LogCompletedTest(name);
        }
    }
}